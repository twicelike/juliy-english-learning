package profile

import (
	"context"
	"time"

	"go.mongodb.org/mongo-driver/v2/bson"
)

// -----------------------------------------------------------------------------
// Domain Models (DB Structs)
// -----------------------------------------------------------------------------

// UserProfile represents the personalized learning state and settings of a user.
type UserProfile struct {
	ID                 bson.ObjectID `bson:"_id,omitempty"`
	UserID             bson.ObjectID `bson:"user_id"`
	PlacementScore     int           `bson:"placement_score"`
	CurrentCEFR        string        `bson:"current_cefr"` // A1, A2, B1, B2, C1, C2
	DailyGoal          int           `bson:"daily_goal"`
	CompletedPlacement bool          `bson:"completed_placement"`
	LastAssessmentAt   time.Time     `bson:"last_assessment_at"`
	Strengths          []string      `bson:"strengths"`  // E.g. ["Business", "Noun"]
	Weaknesses         []string      `bson:"weaknesses"` // E.g. ["Technology", "Verb"]
	CreatedAt          time.Time     `bson:"created_at"`
	UpdatedAt          time.Time     `bson:"updated_at"`
}

// -----------------------------------------------------------------------------
// DTOs (Data Transfer Objects)
// -----------------------------------------------------------------------------

// UserProfileDTO is the external representation of a UserProfile.
type UserProfileDTO struct {
	CurrentCEFR        string   `json:"current_cefr"`
	DailyGoal          int      `json:"daily_goal"`
	CompletedPlacement bool     `json:"completed_placement"`
	Strengths          []string `json:"strengths"`
	Weaknesses         []string `json:"weaknesses"`
}

// RecommendationAction defines what type of action the UI should render.
type RecommendationAction string

const (
	ActionReview    RecommendationAction = "review"
	ActionLearnNew  RecommendationAction = "learn_new"
	ActionGrammar   RecommendationAction = "grammar"
	ActionFillBlank RecommendationAction = "fill_blank"
	ActionDone      RecommendationAction = "done" // Daily goal met, no immediate action needed
)

// RecommendationResponse represents the Next Best Action for the user.
type RecommendationResponse struct {
	Action      RecommendationAction `json:"action"`
	Title       string               `json:"title"`
	Description string               `json:"description"`
	Count       int                  `json:"count"`      // Relevant for review/learn actions
	AIMessage   string               `json:"ai_message"` // Encouraging message generated by AI
}

// DashboardStatistics holds learning stats.
type DashboardStatistics struct {
	WordsLearned int `json:"words_learned"`
	ReviewsDue   int `json:"reviews_due"`
	Accuracy     int `json:"accuracy"` // e.g. 85
}

// DashboardGamification holds gamification progress.
type DashboardGamification struct {
	Level         int         `json:"level"`
	CurrentXP     int         `json:"current_xp"`
	NextLevelXP   int         `json:"next_level_xp"`
	Streak        int         `json:"streak"`
	DailyGoalMet  bool        `json:"daily_goal_met"`
	TodayProgress int         `json:"today_progress"`
	DailyGoal     int         `json:"daily_goal"`
	Achievements  interface{} `json:"achievements"` // []gamification.AchievementDef
}

// DashboardResponse contains the profile info and the recommendation.
type DashboardResponse struct {
	Profile        UserProfileDTO         `json:"profile"`
	Statistics     DashboardStatistics    `json:"statistics"`
	Charts         interface{}            `json:"charts"` // will be []gamification.ChartDataPoint, but we use interface to avoid cyclic import or we can import gamification
	Gamification   DashboardGamification  `json:"gamification"`
	Recommendation RecommendationResponse `json:"recommendation"`
}

// QuestionType enumerates the types of placement questions.
type QuestionType string

const (
	TypeSynonym  QuestionType = "synonym"
	TypeFill     QuestionType = "fill_blank"
	TypeGrammar  QuestionType = "grammar"
)

// PlacementQuestionDTO represents a single question in the placement test.
type PlacementQuestionDTO struct {
	ID            string       `json:"id"`
	Type          QuestionType `json:"type"`
	Question      string       `json:"question"`
	Options       []string     `json:"options"`
	// Note: CorrectAnswer is omitted from the DTO so the frontend doesn't know it.
}

// PlacementTestResponse is returned when the user requests a new placement test.
type PlacementTestResponse struct {
	Questions []PlacementQuestionDTO `json:"questions"`
}

// SubmitTestRequest is sent when the user submits their placement test answers.
type SubmitTestRequest struct {
	Answers map[string]string `json:"answers" binding:"required"` // question_id -> selected_option
}

// SubmitTestResponse is returned after the test is graded.
type SubmitTestResponse struct {
	Score int    `json:"score"`
	CEFR  string `json:"cefr"`
}

// -----------------------------------------------------------------------------
// Interfaces
// -----------------------------------------------------------------------------

type Repository interface {
	GetByUserID(ctx context.Context, userID bson.ObjectID) (*UserProfile, error)
	Upsert(ctx context.Context, profile *UserProfile) error
	EnsureIndexes(ctx context.Context) error
}

type Service interface {
	GetProfile(ctx context.Context, userID string) (*UserProfileDTO, error)
	GetDashboard(ctx context.Context, userID string) (*DashboardResponse, error)
	GetPlacementTest(ctx context.Context) (*PlacementTestResponse, error)
	SubmitPlacementTest(ctx context.Context, userID string, req *SubmitTestRequest) (*SubmitTestResponse, error)
}
